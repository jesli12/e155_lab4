int main(void) {
    configureFlash();
    configureClock();

    // Turn on clock to GPIOB
    RCC->AHB2ENR |= (1 << 1);

    initDuration();
    initPitch();
    
    // Set LED_PIN as output
    pinMode(PIN_OUT, GPIO_OUTPUT);
    
    runDuration(10);

    for(int i = 0; i < (sizeof(notes2)/sizeof(notes2[0])); i++){
      runDuration(notes2[i][1]);
      while (!((TIM15->SR >> 0) & 1)){
        playPitch(notes2[i][0]);
        if (notes2[i][0] == 0){
          TIM16->SR &= ~(1 << 0);
        }else{
          while(!((TIM16->SR >> 0) & 1)){}
          togglePin(PIN_OUT);
          TIM16->SR &= ~(1 << 0);
        }
      }
      TIM15->SR &= ~(1 << 0);
    }
    return 0;
}






