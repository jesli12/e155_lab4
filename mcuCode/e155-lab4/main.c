int main(void) {
    configureFlash();
    configureClock();

    // Turn on clock to GPIOB
    RCC->AHB2ENR |= (1 << 1);

    initDuration();
    initPitch();
    
    // Set LED_PIN as output
    pinMode(PIN_OUT, GPIO_OUTPUT);

    for(int i = 0; i < (sizeof(notes)/sizeof(notes[0])); i++){
      runDuration(notes[i][0]);
      while ((TIM15->SR >> 0) & 1){
        playPitch(notes[i][1]);
        if ((TIM16->SR >> 0) & 1){
            togglePin(PIN_OUT);
        }
      }
    }
    return 0;
}






